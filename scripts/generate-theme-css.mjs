/**
 * Emits dist/theme.css from the compiled tokens so the plain-CSS path and the
 * React `HakiProvider` path can never drift. Runs after tsup, and imports
 * dist/tokens.js — which is deliberately React-free so Node can load it.
 *
 * The variables written here are exactly the ones HakiProvider sets inline on
 * its wrapper div (see src/components/theme-provider.tsx).
 */
import { mkdir, writeFile } from "node:fs/promises";
import { dirname, resolve } from "node:path";
import { fileURLToPath, pathToFileURL } from "node:url";

const root = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const importDist = (file) =>
  import(pathToFileURL(resolve(root, "dist", file)).href);

const {
  lightNeutrals,
  darkNeutrals,
  defaultThemeTokens,
  LIGHT_CHART_COLORS,
  DARK_CHART_COLORS,
} = await importDist("tokens.js");
const { hexToRgb } = await importDist("hex-to-rgb.js");

const neutralVars = (n) => [
  ["--bg", n.bg],
  ["--bg-soft", n.bgSoft],
  ["--surface", n.surface],
  ["--border", n.border],
  ["--input", n.input],
  ["--text", n.text],
  ["--text-muted", n.textMuted],
  ["--hover", n.hover],
];

const chartVars = (colors) =>
  colors.map((color, i) => [`--chart-${i + 1}`, color]);

const block = (selector, pairs, extra = []) =>
  [
    `${selector} {`,
    ...pairs.map(([key, value]) => `  ${key}: ${value};`),
    ...extra.map((line) => `  ${line}`),
    "}",
  ].join("\n");

const t = defaultThemeTokens;
const brandVars = [
  ["--ui-primary", t.primaryColor],
  ["--ui-primary-rgb", hexToRgb(t.primaryColor)],
  [
    "--ui-gradient",
    `linear-gradient(to right, ${t.primaryColor}, ${t.gradientColor})`,
  ],
  ["--ui-primary-bg", t.useGradient ? "var(--ui-gradient)" : "var(--ui-primary)"],
  ["--ui-font", t.fontFamily],
  ["--ui-radius", `${t.borderRadius}px`],
];

const css = `/* Generated by scripts/generate-theme-css.mjs — do not edit by hand.
 *
 * HakiUI design tokens as plain CSS custom properties. Import this when you
 * are NOT using the React <HakiProvider> (e.g. plain HTML, or HTML + your own
 * Tailwind build). Override any variable on :root to retheme.
 *
 * Dark mode: add class="dark" to <html> or <body>, or to any wrapper element.
 */

${block(":root", [...brandVars, ...neutralVars(lightNeutrals), ...chartVars(LIGHT_CHART_COLORS)], ["color: var(--text);"])}

${block(".dark", [...neutralVars(darkNeutrals), ...chartVars(DARK_CHART_COLORS)], ["color: var(--text);"])}
`;

const outputPath = resolve(root, "dist/theme.css");
await mkdir(dirname(outputPath), { recursive: true });
await writeFile(outputPath, css, "utf8");
console.log(`CSS  dist/theme.css   ${(css.length / 1024).toFixed(2)} KB`);
